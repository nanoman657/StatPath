# Writes http.bend: plain HTTP/1.0 over TCP, for the revocation fetches (a CRL from a
# distribution point, an OCSP answer from the responder). A URL is http://a.b.c.d[:port][/path]:
# the kit has no DNS, so the host must be an IP address. The reply is read until the server
# closes, in a chain of K stages (one 16 KB read each), so no IO function is recursive (Bend's
# checker takes no cycles through definitions, as in gen_client.py). Each read waits at most
# RECV_MS milliseconds (TCP.try_recv_bytes): a server that goes silent ends the reply there, and
# a reply that is cut short fails its check (a truncated CRL or OCSP reply does not verify), so
# the chain is refused.
#   python3 -I gen_http.py
K = 64
RECV_MS = 5000

def read_stage(k):
    return f"""def http.r{k}(s: Socket, +acc: List<&2, U32>) -> IO(Socket & List<&2, U32>):
  do IO<Socket & List<&2, U32>>:
    m : Socket & Poll<&1, &1, Result<&1, &1, U32 & String, Maybe<&1, List<&2, U32>>>, Unit> <- TCP.try_recv_bytes(s, 16384, {RECV_MS})
    http.r{k}.got(m, acc)

def http.r{k}.got(m: Socket & Poll<&1, &1, Result<&1, &1, U32 & String, Maybe<&1, List<&2, U32>>>, Unit>, +acc: List<&2, U32>) -> IO(Socket & List<&2, U32>):
  (s, p) = m
  http.r{k}.at(p, s, acc)

def http.r{k}.at(p: Poll<&1, &1, Result<&1, &1, U32 & String, Maybe<&1, List<&2, U32>>>, Unit>, s: Socket, +acc: List<&2, U32>) -> IO(Socket & List<&2, U32>):
  match p:
    case Wait{{u}}:
      IO.pure(Socket & List<&2, U32>, (s, acc))
    case Ready{{r}}:
      http.r{k}.res(r, s, acc)

def http.r{k}.res(r: Result<&1, &1, U32 & String, Maybe<&1, List<&2, U32>>>, s: Socket, +acc: List<&2, U32>) -> IO(Socket & List<&2, U32>):
  match r:
    case Fail{{(code, message)}}:
      IO.pure(Socket & List<&2, U32>, (s, acc))
    case Done{{None{{}}}}:
      IO.pure(Socket & List<&2, U32>, (s, acc))
    case Done{{Some{{+chunk}}}}:
      http.r{k + 1}(s, List.append(&2, U32, acc, chunk))

"""

stages = "".join(read_stage(k) for k in range(K))
stages += f"""def http.r{K}(s: Socket, +acc: List<&2, U32>) -> IO(Socket & List<&2, U32>):
  IO.pure(Socket & List<&2, U32>, (s, acc))

"""

body = r'''# http.bend: plain HTTP/1.0 over TCP, for the revocation fetches (generated by gen_http.py).
#   a URL is http://a.b.c.d[:port][/path]; http.call sends a request and returns the reply body
#   when the status is 200 (the connection closes after the reply: HTTP/1.0).

import Base
import ./sha256.bend as S
import ./rsa.bend as R

type Url is Data:
  Url{ip: List<&2, U32>, port: Nat, path: List<&2, U32>}

# the bytes of an ASCII string literal
def http.b(s: String) -> List<&2, U32>:
  S.bytes_of(s)

# the bytes before the first one equal to c (c is not included); the select is one call per byte
def http.before(+xs: List<&2, U32>, +c: U32) -> List<&2, U32>:
  match xs:
    case Nil{}:
      Nil{}
    case +x <> t:
      Bool.pick(List<&2, U32>, U32.is_eq(x, c), Nil{}, x <> http.before(t, c))

# the bytes from the first one equal to c on (c included), or Nil when there is none
def http.from(+xs: List<&2, U32>, +c: U32) -> List<&2, U32>:
  match xs:
    case Nil{}:
      Nil{}
    case +x <> t:
      Bool.pick(List<&2, U32>, U32.is_eq(x, c), x <> t, http.from(t, c))

# the decimal number written by a list of digit bytes
def http.num(+xs: List<&2, U32>, acc: Nat) -> Nat:
  match xs:
    case Nil{}:
      acc
    case +x <> t:
      http.num(t, Nat.add(Nat.mul(acc, 10n), U32.to_nat(U32.sub(x, 48))))

# the bytes of an address: digits and dots only, with three dots (one recursive call per byte)
def http.ip_ok.at(+xs: List<&2, U32>, +dots: U32) -> Bool:
  match xs:
    case Nil{}:
      U32.is_eq(dots, 3)
    case +x <> t:
      Bool.and(Bool.or(U32.is_eq(x, 46), Bool.and(U32.is_le(48, x), U32.is_le(x, 57))),
        http.ip_ok.at(t, U32.add(dots, Bool.to_u32(U32.is_eq(x, 46)))))

def http.ip_ok(+xs: List<&2, U32>) -> Bool:
  http.ip_ok.at(xs, 0)

# the port of the authority (after the colon), or 80 when there is none
def http.port(+auth: List<&2, U32>) -> Nat:
  http.port.at(http.from(auth, 58))

def http.port.at(+colon: List<&2, U32>) -> Nat:
  match colon:
    case Nil{}:
      80n
    case +c <> digits:
      http.num(digits, 0n)

# the path, from the slash on, or "/" when there is none
def http.path.at(+rest: List<&2, U32>) -> List<&2, U32>:
  match rest:
    case Nil{}:
      47 <> Nil{}
    case +p <> t:
      rest

# http://host[:port][/path]
def http.url(+u: List<&2, U32>) -> Maybe<&2, Url>:
  http.url.at(R.rsa.eqb(List.take(&2, U32, u, 7n), http.b("http://")), u)

def http.url.at(prefix: Bool, +u: List<&2, U32>) -> Maybe<&2, Url>:
  match prefix:
    case True{}:
      http.url.parts(List.drop(&2, U32, u, 7n))
    case False{}:
      None{}

def http.url.parts(+rest: List<&2, U32>) -> Maybe<&2, Url>:
  http.url.check(http.ip_ok(http.before(http.before(rest, 47), 58)), http.before(rest, 47), rest)

def http.url.check(ip: Bool, +auth: List<&2, U32>, +rest: List<&2, U32>) -> Maybe<&2, Url>:
  match ip:
    case True{}:
      Some{Url{http.before(auth, 58), http.port(auth), http.path.at(http.from(rest, 47))}}
    case False{}:
      None{}

# the address as a string ("a.b.c.d"), for the connection
def http.ip_str(+bs: List<&2, U32>) -> String:
  match bs:
    case Nil{}:
      SNil{}
    case +x <> t:
      SCon{Chr{x}, http.ip_str(t)}

# the reply: its body when the status line is HTTP/1.x 200, else None
def http.reply(+bs: List<&2, U32>) -> Maybe<&2, List<&2, U32>>:
  http.reply.at(R.rsa.eqb(List.take(&2, U32, bs, 7n), http.b("HTTP/1.")),
    R.rsa.eqb(List.take(&2, U32, List.drop(&2, U32, bs, 9n), 3n), http.b("200")), bs)

def http.reply.at(version: Bool, status: Bool, +bs: List<&2, U32>) -> Maybe<&2, List<&2, U32>>:
  match version:
    case True{}:
      http.reply.status(status, bs)
    case False{}:
      None{}

def http.reply.status(status: Bool, +bs: List<&2, U32>) -> Maybe<&2, List<&2, U32>>:
  match status:
    case True{}:
      http.reply.body(http.after_head(bs))
    case False{}:
      None{}

# the bytes after the first blank line (CRLF CRLF)
def http.after_head(+bs: List<&2, U32>) -> Maybe<&2, List<&2, U32>>:
  match bs:
    case Nil{}:
      None{}
    case 13 <> 10 <> 13 <> 10 <> body:
      Some{body}
    case x <> t:
      http.after_head(t)

def http.reply.body(+body: Maybe<&2, List<&2, U32>>) -> Maybe<&2, List<&2, U32>>:
  body

# the request: METHOD path HTTP/1.0, the host, the connection is closed after the reply, and the body
def http.request(method: String, +u: Url, ctype: String, +body: List<&2, U32>) -> List<&2, U32>:
  match u:
    case Url{+ip, +port, +path}:
      List.append(&2, U32, http.b(method), List.append(&2, U32, http.b(" "), List.append(&2, U32, path,
        List.append(&2, U32, http.b(" HTTP/1.0\r\nHost: "), List.append(&2, U32, ip,
        List.append(&2, U32, http.b("\r\nConnection: close\r\n"), http.request.body(ctype, body)))))))

def http.request.body(ctype: String, +body: List<&2, U32>) -> List<&2, U32>:
  http.request.body.at(List.length(&2, U32, body), ctype, body)

def http.request.body.at(n: Nat, ctype: String, +body: List<&2, U32>) -> List<&2, U32>:
  match n:
    case 0n:
      http.b("\r\n")
    case 1n+_:
      List.append(&2, U32, http.b("Content-Type: "), List.append(&2, U32, http.b(ctype),
        List.append(&2, U32, http.b("\r\nContent-Length: "), List.append(&2, U32, http.b(Nat.show(n)),
        List.append(&2, U32, http.b("\r\n\r\n"), body)))))

# sending the request: a failed send closes the connection and stops the program
def http.send(s: Socket, +data: List<&2, U32>) -> IO(Socket):
  do IO<Socket>:
    sent : Socket & Result<&1, &1, (U32 & String) & List<&2, U32>, Unit> <- TCP.send_bytes(s, data)
    http.send.done(sent)

def http.send.done(m: Socket & Result<&1, &1, (U32 & String) & List<&2, U32>, Unit>) -> IO(Socket):
  (s, r) = m
  match r:
    case Fail{((code, message), rest)}:
      do IO<Socket>:
        Socket.close(s)
        IO.die(Socket, code, message)
    case Done{_}:
      IO.pure(Socket, s)

# the reply: the reads until the server closes, then the body if the status is 200
def http.done(t: Socket & List<&2, U32>) -> IO(Maybe<&2, List<&2, U32>>):
  (s, acc) = t
  do IO<Maybe<&2, List<&2, U32>>>:
    Socket.close(s)
    IO.pure(Maybe<&2, List<&2, U32>>, http.reply(acc))

# one request to the URL: the body of the reply when it is a 200, else None; a connection that
# cannot be made stops the program (the caller fails the handshake on it)
def http.call(+u: Url, +req: List<&2, U32>) -> IO(Maybe<&2, List<&2, U32>>):
  match u:
    case Url{+ip, +port, +path}:
      http.call.at(http.ip_str(ip), port, req)

def http.call.at(addr: String, port: Nat, +req: List<&2, U32>) -> IO(Maybe<&2, List<&2, U32>>):
  do IO<Maybe<&2, List<&2, U32>>>:
    c : Result<&1, &1, U32 & String, Socket> <- TCP.connect(addr, U32.from_nat(port))
    http.connect.got(c, req)

# a connection that is refused or times out is no reply (None), so the caller refuses the chain
# instead of the runtime stopping
def http.connect.got(c: Result<&1, &1, U32 & String, Socket>, +req: List<&2, U32>) -> IO(Maybe<&2, List<&2, U32>>):
  match c:
    case Fail{(code, message)}:
      IO.pure(Maybe<&2, List<&2, U32>>, None{})
    case Done{s}:
      http.call.go(s, req)

def http.call.go(s: Socket, +req: List<&2, U32>) -> IO(Maybe<&2, List<&2, U32>>):
  do IO<Maybe<&2, List<&2, U32>>>:
    s1 : Socket <- http.send(s, req)
    r : Socket & List<&2, U32> <- http.r0(s1, Nil{})
    http.done(r)

'''
