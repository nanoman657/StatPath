# Writes aes_tests.bend: AES-128 block encryption and AES-128-GCM seal and open.
# Expected values come from the cryptography package. Before any are written,
# the oracle is checked against the published FIPS 197 C.1 block and the
# McGrew-Viega GCM test cases 1 and 2.
#   python3 -I gen_aes_tests.py
import random
from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes
from cryptography.hazmat.primitives.ciphers.aead import AESGCM

def lst(b):
    return "[" + ", ".join(str(x) for x in b) + "]"

def block_enc(key, block):
    c = Cipher(algorithms.AES(key), modes.ECB()).encryptor()
    return c.update(block) + c.finalize()

# FIPS 197 C.1
fips_key = bytes(range(16))
fips_pt = bytes.fromhex("00112233445566778899aabbccddeeff")
assert block_enc(fips_key, fips_pt).hex() == "69c4e0d86a7b0430d8cdb78070b4c55a"
# McGrew-Viega test cases 1 and 2: key 0, IV 0
assert AESGCM(bytes(16)).encrypt(bytes(12), b"", None).hex() == "58e2fccefa7e3061367f1d57a4e7455a"
two = AESGCM(bytes(16)).encrypt(bytes(12), bytes(16), None)
assert two.hex() == "0388dace60b6a392f328c2b971b2fe78ab6e47d42cec13bdf53a67b21257bddf"

rng = random.Random(197)
def rb(n):
    return bytes(rng.randrange(256) for _ in range(n))

out = []
def kc(name, expr, want):
    out.append(f'  kcase("{name}", {expr}, "{want}") <>')

def hexof(expr):
    return f"S.hex_of({expr})"

kc("fips197-c1", hexof(f"AES.aes.enc(AES.aes.expand({lst(fips_key)}), {lst(fips_pt)})"),
   block_enc(fips_key, fips_pt).hex())
for i in range(6):
    key = rb(16); blk = rb(16)
    kc(f"block-{i}", hexof(f"AES.aes.enc(AES.aes.expand({lst(key)}), {lst(blk)})"),
       block_enc(key, blk).hex())

# GCM seal: the McGrew-Viega cases, then random keys, nonces, AAD and lengths
kc("gcm-mv1", hexof(f"G.gcm.seal({lst(bytes(16))}, {lst(bytes(12))}, [], [])"),
   AESGCM(bytes(16)).encrypt(bytes(12), b"", None).hex())
kc("gcm-mv2", hexof(f"G.gcm.seal({lst(bytes(16))}, {lst(bytes(12))}, [], {lst(bytes(16))})"),
   two.hex())
sealed_for = {}
for aad_n in [0, 5, 16, 33]:
    for pt_n in [0, 1, 15, 16, 17, 40]:
        key = rb(16); nonce = rb(12); aad = rb(aad_n); pt = rb(pt_n)
        want = AESGCM(key).encrypt(nonce, pt, aad if aad_n else None).hex()
        kc(f"gcm-a{aad_n}-p{pt_n}",
           hexof(f"G.gcm.seal({lst(key)}, {lst(nonce)}, {lst(aad)}, {lst(pt)})"), want)
        if pt_n == 17 and aad_n == 16:
            sealed_for = dict(key=key, nonce=nonce, aad=aad, sealed=AESGCM(key).encrypt(nonce, pt, aad))

# GCM open: the genuine sealed text opens; a changed tag, body or AAD does not
k, n, a, s = sealed_for["key"], sealed_for["nonce"], sealed_for["aad"], sealed_for["sealed"]
def boolcase(name, expr, want):
    out.append(f'  kcase("{name}", Bool.show({expr}), "{want}") <>')
boolcase("open-genuine", f"G.gcm.valid({lst(k)}, {lst(n)}, {lst(a)}, {lst(s)})", "True")
tag_bad = s[:-1] + bytes([s[-1] ^ 1])
boolcase("open-tag-changed", f"G.gcm.valid({lst(k)}, {lst(n)}, {lst(a)}, {lst(tag_bad)})", "False")
body_bad = bytes([s[0] ^ 0x80]) + s[1:]
boolcase("open-body-changed", f"G.gcm.valid({lst(k)}, {lst(n)}, {lst(a)}, {lst(body_bad)})", "False")
boolcase("open-aad-changed", f"G.gcm.valid({lst(k)}, {lst(n)}, {lst(a[:-1] + bytes([a[-1] ^ 1]))}, {lst(s)})", "False")
boolcase("open-too-short", f"G.gcm.valid({lst(k)}, {lst(n)}, {lst(a)}, {lst(s[:10])})", "False")
# the open result is the plaintext: the sealed text of random data round-trips
pt = rb(40)
rt_sealed = AESGCM(k).encrypt(n, pt, a)
kc("open-roundtrip", hexof(f"G.gcm.crypt({lst(k)}, {lst(n)}, {lst(pt)})"),
   AESGCM(k).encrypt(n, pt, None)[:-16].hex())

src = r'''# aes_tests.bend: AES-128 blocks and AES-128-GCM (generated by gen_aes_tests.py).
#   bend aes_tests.bend

import Base
import ./sha256.bend as S
import ./aes.bend as AES
import ./gcm.bend as G

type Case is Data:
  Case{name: String, got: String, want: String}

def kcase(name: String, +got: String, want: String) -> Case:
  Case{name, got, want}

def cases() -> List<&2, Case>:
''' + "\n".join(out) + r'''
  Nil{}

def fails.at(+c: Case, +rest: List<&2, String>) -> List<&2, String>:
  match c:
    case Case{n, +g, +w}:
      Bool.pick(List<&2, String>, String.eq(g, w), rest,
        ("FAIL " ++ n ++ "\n  got:  " ++ g ++ "\n  want: " ++ w) <> rest)

def fails(cs: List<&2, Case>) -> List<&2, String>:
  match cs:
    case Nil{}:
      Nil{}
    case +c <> t:
      fails.at(c, fails(t))

def main() -> IO(Unit):
  +cs = cases()
  +n = List.length(&2, Case, cs)
  +fs = fails(cs)
  +f = List.length(&2, String, fs)
  do IO<Unit>:
    List.for_each(~&2, ~String, ~IO.print, fs)
    IO.print("aes-gcm: " ++ Nat.show(Nat.sub(n, f)) ++ " passed, " ++ Nat.show(f) ++ " failed")
'''
open("aes_tests.bend", "w").write(src)
print(len(out), "cases")
