# Writes x509_tests.bend: X.509 parsing and verification against certificates
# made by the cryptography package: a root CA, an intermediate CA, a leaf for
# example.test, and an expired leaf. Each expected answer is fixed by how the
# certificate was built.
#   python3 -I gen_x509_tests.py
import datetime as dt
from cryptography import x509 as cx
from cryptography.x509.oid import NameOID
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import rsa

def lst(b):
    return "[" + ", ".join(str(x) for x in b) + "]"

def name(cn):
    return cx.Name([cx.NameAttribute(NameOID.COMMON_NAME, cn)])

def make(subject, key, issuer_name, issuer_key, nb, na, ca=False, san=None):
    b = (cx.CertificateBuilder().subject_name(name(subject)).issuer_name(issuer_name)
         .public_key(key.public_key()).serial_number(cx.random_serial_number())
         .not_valid_before(nb).not_valid_after(na))
    if ca:
        b = b.add_extension(cx.BasicConstraints(ca=True, path_length=None), critical=True)
    if san:
        b = b.add_extension(cx.SubjectAlternativeName([cx.DNSName(s) for s in san]), critical=False)
    return b.sign(issuer_key, hashes.SHA256())

y = dt.datetime(2026, 1, 1, tzinfo=dt.timezone.utc)
root_key = rsa.generate_private_key(65537, 2048)
inter_key = rsa.generate_private_key(65537, 2048)
leaf_key = rsa.generate_private_key(65537, 2048)
root = make("Test Root", root_key, name("Test Root"), root_key,
            dt.datetime(2025, 1, 1, tzinfo=dt.timezone.utc), dt.datetime(2035, 1, 1, tzinfo=dt.timezone.utc), ca=True)
inter = make("Test Intermediate", inter_key, root.subject, root_key, y - dt.timedelta(days=30),
             dt.datetime(2032, 1, 1, tzinfo=dt.timezone.utc), ca=True)
leaf = make("example.test", leaf_key, inter.subject, inter_key, y, dt.datetime(2030, 1, 1, tzinfo=dt.timezone.utc),
            san=["example.test", "www.example.test"])
old = make("expired.test", leaf_key, inter.subject, inter_key,
           dt.datetime(2019, 1, 1, tzinfo=dt.timezone.utc), dt.datetime(2020, 1, 1, tzinfo=dt.timezone.utc),
           san=["expired.test"])
other_root_key = rsa.generate_private_key(65537, 2048)
other_root = make("Other Root", other_root_key, name("Other Root"), other_root_key,
                  dt.datetime(2025, 1, 1, tzinfo=dt.timezone.utc), dt.datetime(2035, 1, 1, tzinfo=dt.timezone.utc), ca=True)

def der(c):
    return list(c.public_bytes(serialization.Encoding.DER))

NOW = int(dt.datetime(2027, 6, 1, tzinfo=dt.timezone.utc).timestamp())
PAST_EXPIRY = int(dt.datetime(2019, 6, 1, tzinfo=dt.timezone.utc).timestamp())

L, I, R, O, OR = der(leaf), der(inter), der(root), der(old), der(other_root)
host = lambda s: lst(list(s.encode()))
cases = [
    ("dns-names-leaf", f"X.x509.names_host({host('example.test')}, X.x509.dns_names({lst(L)}))", "True"),
    ("host-www", f"X.x509.names_host({host('www.example.test')}, X.x509.dns_names({lst(L)}))", "True"),
    ("host-case-insensitive", f"X.x509.names_host({host('EXAMPLE.Test')}, X.x509.dns_names({lst(L)}))", "True"),
    ("host-wrong", f"X.x509.names_host({host('other.test')}, X.x509.dns_names({lst(L)}))", "False"),
    ("valid-now", f"X.x509.valid({lst(L)}, {NOW}n)", "True"),
    ("expired-now", f"X.x509.valid({lst(O)}, {NOW}n)", "False"),
    ("expired-at-2021", f"X.x509.valid({lst(O)}, {PAST_EXPIRY}n)", "True"),
    ("sig-leaf-by-inter", f"X.x509.sigok({lst(L)}, {lst(I)})", "True"),
    ("sig-inter-by-root", f"X.x509.sigok({lst(I)}, {lst(R)})", "True"),
    ("sig-leaf-by-root-wrong", f"X.x509.sigok({lst(L)}, {lst(R)})", "False"),
    ("sig-leaf-by-other-root", f"X.x509.sigok({lst(L)}, {lst(OR)})", "False"),
    ("chain-to-root", f"X.x509.verify_server([{lst(L)}, {lst(I)}], [{lst(R)}], {host('example.test')}, {NOW}n)", "True"),
    ("chain-wrong-anchor", f"X.x509.verify_server([{lst(L)}, {lst(I)}], [{lst(OR)}], {host('example.test')}, {NOW}n)", "False"),
    ("chain-wrong-host", f"X.x509.verify_server([{lst(L)}, {lst(I)}], [{lst(R)}], {host('other.test')}, {NOW}n)", "False"),
    ("chain-expired-leaf", f"X.x509.verify_server([{lst(O)}, {lst(I)}], [{lst(R)}], {host('expired.test')}, {NOW}n)", "False"),
    ("chain-missing-intermediate", f"X.x509.verify_server([{lst(L)}], [{lst(R)}], {host('example.test')}, {NOW}n)", "False"),
    ("anchor-is-leaf", f"X.x509.verify_server([{lst(L)}], [{lst(L)}], {host('example.test')}, {NOW}n)", "True"),
]

body = [f'  kcase("{n}", Bool.show({e}), "{w}") <>' if not e.startswith("X.x509.names_host")
        else f'  kcase("{n}", Bool.show({e}), "{w}") <>' for n, e, w in cases]
src = '''# x509_tests.bend: X.509 parsing and verification (generated by gen_x509_tests.py).
#   bend x509_tests.bend

import Base
import ./x509.bend as X

type Case is Data:
  Case{name: String, got: String, want: String}

def kcase(name: String, +got: String, want: String) -> Case:
  Case{name, got, want}

def cases() -> List<&2, Case>:
''' + "\n".join(body) + '''
  Nil{}

def fails.at(+c: Case, +rest: List<&2, String>) -> List<&2, String>:
  match c:
    case Case{n, +g, +w}:
      Bool.pick(List<&2, String>, String.eq(g, w), rest,
        ("FAIL " ++ n ++ "\\n  got:  " ++ g ++ "\\n  want: " ++ w) <> rest)

def fails(cs: List<&2, Case>) -> List<&2, String>:
  match cs:
    case Nil{}:
      Nil{}
    case +c <> t:
      fails.at(c, fails(t))

def main() -> IO(Unit):
  +cs = cases()
  +n = List.length(&2, Case, cs)
  +fs = fails(cs)
  +f = List.length(&2, String, fs)
  do IO<Unit>:
    List.for_each(~&2, ~String, ~IO.print, fs)
    IO.print("x509: " ++ Nat.show(Nat.sub(n, f)) ++ " passed, " ++ Nat.show(f) ++ " failed")
'''
open("x509_tests.bend", "w").write(src)
open("/tmp/claude-0/probe/pki.txt", "w").write(repr({"leaf": L, "inter": I, "root": R}))
print(len(cases), "cases")
