# Writes sha512_tests.bend: SHA-512 against hashlib, at the padding boundaries and on
# random messages of several block counts.
#   python3 -I gen_sha512_tests.py
import hashlib
import random

def lst(b):
    return "[" + ", ".join(str(x) for x in b) + "]"

rng = random.Random(512)
out = []
def kc(name, msg):
    out.append(f'  kcase("{name}", S.hex_of(SH.sha512.hash({lst(msg)})), "{hashlib.sha512(msg).hexdigest()}") <>')

kc("empty", b"")
kc("abc", b"abc")
kc("nist-896", b"abcdefghbcdefghicdefghijdefghijkefghijklfghijklmghijklmnhijklmnoijklmnopjklmnopqklmnopqrlmnopqrsmnopqrstnopqrstu")
for n in [1, 55, 111, 112, 113, 127, 128, 129, 200, 255, 256, 300]:
    kc(f"len-{n}", bytes(rng.randrange(256) for _ in range(n)))
for n in [0, 3, 80, 1000]:
    kc(f"mixed-{n}", bytes(range(256))[:n] * (1 + n // 256))

src = r'''# sha512_tests.bend: SHA-512 against hashlib (generated by gen_sha512_tests.py).
#   bend sha512_tests.bend

import Base
import ./sha256.bend as S
import ./sha512.bend as SH

type Case is Data:
  Case{name: String, got: String, want: String}

def kcase(name: String, +got: String, want: String) -> Case:
  Case{name, got, want}

def cases() -> List<&2, Case>:
''' + "\n".join(out) + r'''
  Nil{}

def fails.at(+c: Case, +rest: List<&2, String>) -> List<&2, String>:
  match c:
    case Case{n, +g, +w}:
      Bool.pick(List<&2, String>, String.eq(g, w), rest,
        ("FAIL " ++ n ++ "\n  got:  " ++ g ++ "\n  want: " ++ w) <> rest)

def fails(cs: List<&2, Case>) -> List<&2, String>:
  match cs:
    case Nil{}:
      Nil{}
    case +c <> t:
      fails.at(c, fails(t))

def main() -> IO(Unit):
  +cs = cases()
  +n = List.length(&2, Case, cs)
  +fs = fails(cs)
  +f = List.length(&2, String, fs)
  do IO<Unit>:
    List.for_each(~&2, ~String, ~IO.print, fs)
    IO.print("sha512: " ++ Nat.show(Nat.sub(n, f)) ++ " passed, " ++ Nat.show(f) ++ " failed")
'''
open("sha512_tests.bend", "w").write(src)
print(len(out), "cases")
