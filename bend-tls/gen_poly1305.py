# Writes poly1305.bend: arithmetic mod p = 2^130 - 5 (RFC 8439 section 2.5).
# A field element is ten 13-bit limbs of Nat, least significant first. Nat is
# exact here, so the accumulators never overflow. The products and the carry
# chains are generated, one operation per line.
#   python3 -I gen_poly1305.py
L = 10
R = 8192          # 2^13
ops = []
cnt = [0]

def let(expr):
    cnt[0] += 1
    v = f"q{cnt[0]}"
    ops.append(f"  +{v} = ({expr} : Nat)")
    return v

def fields(p):
    return ", ".join(f"+{p}{i}" for i in range(L))

def carry_chain(e, wrap):
    """Sequential carries over limbs e[0..9]; returns (limbs, top carry)."""
    out = []
    carry = None
    for k in range(L):
        cur = e[k] if carry is None else let(f"{e[k]} + {carry}")
        c = let(f"{cur} / {R}n")
        out.append(let(f"{cur} % {R}n"))
        carry = c
    if wrap:
        out[0] = let(f"{out[0]} + 5n * {carry}")
        return out, None
    return out, carry

# pl.mul: schoolbook products, folding limbs i+j >= 10 back with 2^130 = 5
def mul_body():
    raw = []
    for k in range(L):
        terms = [f"a{i} * r{j}" for i in range(L) for j in range(L) if i + j == k]
        wrap = [f"a{i} * r{j}" for i in range(L) for j in range(L) if i + j == k + L]
        expr = " + ".join(terms)
        if wrap:
            expr += " + 5n * (" + " + ".join(wrap) + ")"
        raw.append(let(expr))
    return raw

mul_raw = mul_body()
MUL_OPS = "\n".join(ops); ops.clear()
pass_out, _ = carry_chain([f"x{i}" for i in range(L)], wrap=True)
PASS_OPS = "\n".join(ops); ops.clear()
pass_names = pass_out
nw_out, nw_top = carry_chain([f"x{i}" for i in range(L)], wrap=False)
NW_OPS = "\n".join(ops); ops.clear()

def ctor(names):
    return ", ".join(names)


# pl.bits_of: the low 128 bits of x (x canonical), least significant first
expr = "pl.bits(13n, x9)"
for i in range(8, -1, -1):
    expr = f"pl.cat(pl.bits(13n, x{i}), {expr})"
BITS_OF_DEF = (
    "def pl.cat(+a: List<&2, Nat>, +b: List<&2, Nat>) -> List<&2, Nat>:\n"
    "  List.append(&2, Nat, a, b)\n\n"
    "def pl.bits_of(+x: F) -> List<&2, Nat>:\n"
    "  match x:\n"
    "    case F{" + ", ".join(f"+x{i}" for i in range(L)) + "}:\n"
    "      List.take(&2, Nat, " + expr + ", 128n)\n\n")

TEXT = f"""# poly1305.bend: arithmetic mod p = 2^130 - 5 for Poly1305 (RFC 8439 section
# 2.5). A field element is ten 13-bit limbs of Nat, least significant first.
# Generated by gen_poly1305.py.

import Base

type F is Data:
  F{{l0: Nat, l1: Nat, l2: Nat, l3: Nat, l4: Nat, l5: Nat, l6: Nat, l7: Nat, l8: Nat, l9: Nat}}

def pl.zero() -> F:
  F{{0n, 0n, 0n, 0n, 0n, 0n, 0n, 0n, 0n, 0n}}

def pl.add(+a: F, +b: F) -> F:
  match a:
    case F{{{fields("a")}}}:
      match b:
        case F{{{fields("b")}}}:
          F{{{", ".join(f"(a{i} + b{i} : Nat)" for i in range(L))}}}

# one carry pass, the top carry wrapping into limb 0 as 5 * carry
def pl.pass(+x: F) -> F:
  match x:
    case F{{{fields("x")}}}:
{PASS_OPS}
      F{{{ctor(pass_names)}}}

# two carry passes: every limb back under 2^13 plus a little
def pl.norm(+x: F) -> F:
  pl.pass(pl.pass(x))

# a * r mod p, the products and folds generated
def pl.mul(+a: F, +r: F) -> F:
  match a:
    case F{{{fields("a")}}}:
      match r:
        case F{{{fields("r")}}}:
{MUL_OPS}
          pl.norm(F{{{ctor(mul_raw)}}})

# carries without wrapping: the limbs under 2^13 and the carry out of limb 9
def pl.carrynw(+x: F) -> F & Nat:
  match x:
    case F{{{fields("x")}}}:
{NW_OPS}
      (F{{{ctor(nw_out)}}}, {nw_top})

# x with c added to limb 0
def pl.addl0(+x: F, +c: Nat) -> F:
  match x:
    case F{{{fields("x")}}}:
      F{{(x0 + c : Nat), x1, x2, x3, x4, x5, x6, x7, x8, x9}}

# y < 2^130 is below p, or in [p, 2^130) and then y + 5 carries out of limb 9
# gy where s is 1, y where s is 0, limb by limb with no branch: a * (1 - s) + b * s
def pl.sel(+s: Nat, +y: F, +gy: F) -> F:
  match y:
    case F{{{fields("a")}}}:
      match gy:
        case F{{{fields("b")}}}:
          F{{{", ".join(f"(a{i} * Nat.sub(1n, s) + b{i} * s : Nat)" for i in range(L))}}}

def pl.canon.pick(+y: F, g: F & Nat) -> F:
  (gy, gt) = g
  pl.sel(gt, y, gy)

def pl.first(g: F & Nat) -> F:
  (y, t) = g
  y

def pl.canon.sub(+y: F) -> F:
  pl.canon.pick(y, pl.carrynw(pl.addl0(y, 5n)))

# x mod p, exactly: limbs under 2^13 and the value below p. Each round folds
# the carry out of limb 9 back in (2^130 = 5); four rounds always suffice.
def pl.canon.iter(fuel: Nat, r: F & Nat) -> F:
  match fuel:
    case 0n:
      pl.canon.sub(pl.first(r))
    case 1n+p:
      (y, +t) = r
      pl.canon.iter(p, pl.carrynw(pl.addl0(y, Nat.mul(5n, t))))

def pl.canon(+x: F) -> F:
  pl.canon.iter(4n, pl.carrynw(pl.norm(x)))

# the value of the first k bits of a bit list (weights pw, pw * 2, ...), and
# the list after them
def pl.val(k: Nat, +bits: List<&2, Nat>, +pw: Nat, +acc: Nat) -> Nat:
  match k:
    case 0n:
      acc
    case 1n+p:
      match bits:
        case Nil{{}}:
          acc
        case b <> t:
          pl.val(p, t, Nat.mul(2n, pw), Nat.add(acc, Nat.mul(b, pw)))

def pl.drop(k: Nat, +bits: List<&2, Nat>) -> List<&2, Nat>:
  match k:
    case 0n:
      bits
    case 1n+p:
      match bits:
        case Nil{{}}:
          Nil{{}}
        case b <> t:
          pl.drop(p, t)

# the first n limbs of 13 bits each, least significant first
def pl.limbs(n: Nat, +bits: List<&2, Nat>) -> List<&2, Nat>:
  match n:
    case 0n:
      Nil{{}}
    case 1n+p:
      pl.val(13n, bits, 1n, 0n) <> pl.limbs(p, pl.drop(13n, bits))

def pl.of10(xs: List<&2, Nat>) -> F:
  match xs:
    case x0 <> x1 <> x2 <> x3 <> x4 <> x5 <> x6 <> x7 <> x8 <> x9 <> Nil{{}}:
      F{{x0, x1, x2, x3, x4, x5, x6, x7, x8, x9}}
    case _:
      pl.zero()

# the field element of the first 130 bits of a bit list
def pl.of_bits(+bits: List<&2, Nat>) -> F:
  pl.of10(pl.limbs(10n, bits))

# the k low bits of v, least significant first
def pl.bits(k: Nat, +v: Nat) -> List<&2, Nat>:
  match k:
    case 0n:
      Nil{{}}
    case 1n+p:
      Nat.mod(v, 2n) <> pl.bits(p, Nat.div(v, 2n))

# the bits of a byte list, least significant first within each byte
def pl.bytes_bits(+bs: List<&2, U32>) -> List<&2, Nat>:
  match bs:
    case Nil{{}}:
      Nil{{}}
    case b <> t:
      List.append(&2, Nat, pl.bits(8n, U32.to_nat(b)), pl.bytes_bits(t))

# the field element of little-endian bytes (any length up to 16 bytes plus one)
def pl.of_bytes(+bs: List<&2, U32>) -> F:
  pl.of_bits(pl.bytes_bits(bs))

{BITS_OF_DEF}
# the bytes of a bit list of length 8k, 8 bits each, least significant first
def pl.pack(+bits: List<&2, Nat>) -> List<&2, U32>:
  match bits:
    case Nil{{}}:
      Nil{{}}
    case b0 <> b1 <> b2 <> b3 <> b4 <> b5 <> b6 <> b7 <> t:
      U32.from_nat(Nat.add(b0, Nat.add(Nat.mul(2n, b1), Nat.add(Nat.mul(4n, b2), Nat.add(Nat.mul(8n, b3),
        Nat.add(Nat.mul(16n, b4), Nat.add(Nat.mul(32n, b5), Nat.add(Nat.mul(64n, b6), Nat.mul(128n, b7)))))))))
        <> pl.pack(t)
    case _:
      Nil{{}}
"""
open("poly1305.bend", "w").write(TEXT.replace("{BITS_OF_DEF}", BITS_OF_DEF))
print("ops:", MUL_OPS.count("\n") + PASS_OPS.count("\n") + NW_OPS.count("\n"))
