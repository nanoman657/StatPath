# Writes sha256.bend. The round constants and initial state are computed
# from the primes (cube and square roots, as FIPS 180-4 defines them):
#   python3 -I gen_sha256.py
import math

def icbrt(n):
    x = 1 << (n.bit_length() // 3 + 1)
    while True:
        y = (2 * x + n // (x * x)) // 3
        if y >= x:
            break
        x = y
    while x ** 3 > n:
        x -= 1
    while (x + 1) ** 3 <= n:
        x += 1
    return x

primes = []
c = 2
while len(primes) < 64:
    if all(c % p for p in primes if p * p <= c):
        primes.append(c)
    c += 1
K = [icbrt(p << 96) & 0xffffffff for p in primes]
H = [math.isqrt(p << 64) & 0xffffffff for p in primes[:8]]

def karms():
    return "".join(f"    case {i}n:\n      {k}\n" for i, k in enumerate(K)) + "    case _:\n      0\n"

def wfields(prefix, n):
    return ", ".join(f"{prefix}{i}" for i in range(n))

WIN = wfields("v", 16)
WINP = ", ".join(f"+v{i}" for i in range(16))
ZWIN = ", ".join("0" for _ in range(16))
MKWIN = (" <> ".join(f"v{i}" for i in range(16)) + " <> Nil{}")

src = f'''# sha256.bend: SHA-256 (FIPS 180-4) over bytes, in pure Bend.
#
# A message is a List of bytes (U32 values 0..255). Words are big-endian.
# sha256.bend is generated by gen_sha256.py.

import Base

# Bit operations
# --------------

def rotr(+x: U32, +n: Nat) -> U32:
  U32.or(U32.shrn(x, n), U32.shln(x, Nat.sub(32n, n)))

def bsig0(+x: U32) -> U32:
  U32.xor(U32.xor(rotr(x, 2n), rotr(x, 13n)), rotr(x, 22n))

def bsig1(+x: U32) -> U32:
  U32.xor(U32.xor(rotr(x, 6n), rotr(x, 11n)), rotr(x, 25n))

def ssig0(+x: U32) -> U32:
  U32.xor(U32.xor(rotr(x, 7n), rotr(x, 18n)), U32.shrn(x, 3n))

def ssig1(+x: U32) -> U32:
  U32.xor(U32.xor(rotr(x, 17n), rotr(x, 19n)), U32.shrn(x, 10n))

def ch(+e: U32, +f: U32, +g: U32) -> U32:
  U32.xor(U32.and(e, f), U32.and(U32.not(e), g))

def maj(+a: U32, +b: U32, +c: U32) -> U32:
  U32.xor(U32.xor(U32.and(a, b), U32.and(a, c)), U32.and(b, c))

# Constants: the round constant K_t
# ---------------------------------

def kc(+t: Nat) -> U32:
  match t:
{karms()}
# The state
# ---------

type St is Data:
  St{{a: U32, b: U32, c: U32, d: U32, e: U32, f: U32, g: U32, h: U32}}

# The message schedule window: v0..v15 are W_t .. W_(t+15)
type Win is Data:
  Win{{{", ".join(f"v{i}: U32" for i in range(16))}}}

def iv() -> St:
  St{{{", ".join(f"{h}" for h in H)}}}

def addst(+x: St, +y: St) -> St:
  match x:
    case St{{+a1, +b1, +c1, +d1, +e1, +f1, +g1, +h1}}:
      match y:
        case St{{+a2, +b2, +c2, +d2, +e2, +f2, +g2, +h2}}:
          St{{U32.add(a1, a2), U32.add(b1, b2), U32.add(c1, c2), U32.add(d1, d2),
            U32.add(e1, e2), U32.add(f1, f2), U32.add(g1, g2), U32.add(h1, h2)}}

# One round: t selects K_t, w is W_t
def rnd1(+t: Nat, +st: St, +w: U32) -> St:
  match st:
    case St{{+a, +b, +c, +d, +e, +f, +g, +h}}:
      +t1 = U32.add(U32.add(U32.add(h, bsig1(e)), ch(e, f, g)), U32.add(kc(t), w))
      +t2 = U32.add(bsig0(a), maj(a, b, c))
      St{{U32.add(t1, t2), a, b, c, U32.add(d, t1), e, f, g}}

# n rounds from round t, the schedule window win holding W_t onward
def rounds(n: Nat, +t: Nat, +st: St, +win: Win) -> St:
  match n:
    case 0n:
      st
    case 1n+p:
      match win:
        case Win{{{WINP}}}:
          rounds(p, 1n+t, rnd1(t, st, v0),
            Win{{{", ".join(f"v{i}" for i in range(1, 16))}, U32.add(U32.add(U32.add(ssig1(v14), v9), ssig0(v1)), v0)}})

def compress(+h: St, +win: Win) -> St:
  addst(h, rounds(64n, 0n, h, win))

# Words and blocks
# ----------------

def word4(b0: U32, b1: U32, b2: U32, b3: U32) -> U32:
  U32.or(U32.or(U32.shln(b0, 24n), U32.shln(b1, 16n)), U32.or(U32.shln(b2, 8n), b3))

# the n big-endian words at the front of xs
def words(n: Nat, xs: List<&2, U32>) -> List<&2, U32>:
  match n:
    case 0n:
      Nil{{}}
    case 1n+p:
      match xs:
        case b0 <> b1 <> b2 <> b3 <> t:
          word4(b0, b1, b2, b3) <> words(p, t)
        case _:
          Nil{{}}

def mkwin(ws: List<&2, U32>) -> Win:
  match ws:
    case {MKWIN}:
      Win{{{WIN}}}
    case _:
      Win{{{ZWIN}}}

# n blocks of 64 bytes, each compressed into the state (the message's
# last blocks, after the full ones: see sha256 below)
def blocks(nb: Nat, +xs: List<&2, U32>, h: St) -> St:
  match nb:
    case 0n:
      h
    case 1n+p:
      blocks(p, List.drop(&2, U32, xs, 64n), compress(h, mkwin(words(16n, xs))))

# the first nb full blocks of xs, compressed in order; xs's rest is returned
def full(nb: Nat, +xs: List<&2, U32>, h: St) -> St & List<&2, U32>:
  match nb:
    case 0n:
      (h, xs)
    case 1n+p:
      full(p, List.drop(&2, U32, xs, 64n), compress(h, mkwin(words(16n, xs))))

# Padding
# -------

# the zero bytes between the 0x80 and the length
def padk(+n: Nat) -> Nat:
  Nat.mod(Nat.sub(64n, Nat.mod(Nat.add(n, 9n), 64n)), 64n)

def zeros(k: Nat) -> List<&2, U32>:
  match k:
    case 0n:
      Nil{{}}
    case 1n+p:
      (0 : U32) <> zeros(p)

# the n-byte big-endian value x, in front of acc
def be(k: Nat, +x: Nat, acc: List<&2, U32>) -> List<&2, U32>:
  match k:
    case 0n:
      acc
    case 1n+p:
      be(p, Nat.div(x, 256n), U32.from_nat(Nat.mod(x, 256n)) <> acc)

def pad(msg: List<&2, U32>, +n: Nat) -> List<&2, U32>:
  List.append(&2, U32, msg, (128 : U32) <> List.append(&2, U32, zeros(padk(n)),
    be(8n, Nat.mul(n, 8n), Nil{{}})))

# the number of elements of xs, counted without deep recursion
def count(+xs: List<&2, U32>, acc: Nat) -> Nat:
  match xs:
    case Nil{{}}:
      acc
    case h <> t:
      count(t, 1n+acc)

# the state after the message's rest r (which follows its full blocks) and
# the padding that ends a message of n bytes
def sha256.fin(+n: Nat, r: St & List<&2, U32>) -> St:
  (h, rest) = r
  blocks(Nat.div(Nat.add(Nat.mod(n, 64n), Nat.add(9n, padk(n))), 64n), pad(rest, n), h)

def sha256(+msg: List<&2, U32>) -> St:
  +n = count(msg, 0n)
  sha256.fin(n, full(Nat.div(n, 64n), msg, iv()))

# Output
# ------

def hexc.at(+d: U32, lt: Bool) -> Char:
  match lt:
    case True{{}}:
      Chr{{U32.add(48, d)}}
    case False{{}}:
      Chr{{U32.add(87, d)}}

def hexc(+d: U32) -> Char:
  hexc.at(d, U32.is_lt(d, 10))

# the 4 big-endian bytes of w, in front of acc
def wbytes(+w: U32, acc: List<&2, U32>) -> List<&2, U32>:
  U32.and(U32.shrn(w, 24n), 255) <> U32.and(U32.shrn(w, 16n), 255) <>
    U32.and(U32.shrn(w, 8n), 255) <> U32.and(w, 255) <> acc

# the 32-byte digest of the state
def digest_bytes(+s: St) -> List<&2, U32>:
  match s:
    case St{{+a, +b, +c, +d, +e, +f, +g, +h}}:
      wbytes(a, wbytes(b, wbytes(c, wbytes(d, wbytes(e, wbytes(f, wbytes(g, wbytes(h, Nil{{}}))))))))

# the lowercase hex of one byte, in front of rest
def hexb(+b: U32, rest: String) -> String:
  SCon{{hexc(U32.shrn(b, 4n)), SCon{{hexc(U32.and(b, 15)), rest}}}}

def hex_of(bs: List<&2, U32>) -> String:
  match bs:
    case Nil{{}}:
      SNil{{}}
    case b <> t:
      hexb(b, hex_of(t))

# the SHA-256 digest of the bytes msg
def sha256_bytes(+msg: List<&2, U32>) -> List<&2, U32>:
  digest_bytes(sha256(msg))

# the SHA-256 digest of the bytes msg, as 64 hex digits
def sha256_hex(+msg: List<&2, U32>) -> String:
  hex_of(sha256_bytes(msg))

# the bytes of a String (each char's code, which must be below 256)
def bytes_of(s: String) -> List<&2, U32>:
  match s:
    case SNil{{}}:
      Nil{{}}
    case SCon{{c, t}}:
      Char.to_u32(c) <> bytes_of(t)
'''
open('sha256.bend','w').write(src)
