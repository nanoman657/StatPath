# Writes aead_tests.bend: ChaCha20 blocks, Poly1305 tags and ChaCha20-Poly1305
# seal/open. Expected values come from the cryptography package. The RFC 8439
# section 2.8.2 tag is checked against its published value first.
#   python3 -I gen_aead_tests.py
import random
from cryptography.hazmat.primitives.ciphers import Cipher
from cryptography.hazmat.primitives.ciphers.algorithms import ChaCha20
from cryptography.hazmat.primitives.ciphers.aead import ChaCha20Poly1305
from cryptography.hazmat.primitives.poly1305 import Poly1305

def lst(b):
    return "[" + ", ".join(str(x) for x in b) + "]"

def keystream(key, counter, nonce, n):
    c = Cipher(ChaCha20(key, counter.to_bytes(4, "little") + nonce), mode=None)
    return c.encryptor().update(bytes(n))

def poly(key32, msg):
    p = Poly1305(key32)
    p.update(msg)
    return p.finalize()

# RFC 8439 section 2.8.2
rfc_key = bytes(range(0x80, 0xA0))
rfc_nonce = bytes.fromhex("070000004041424344454647")
rfc_aad = bytes.fromhex("50515253c0c1c2c3c4c5c6c7")
rfc_pt = (b"Ladies and Gentlemen of the class of '99: If I could offer you only one tip "
          b"for the future, sunscreen would be it.")
rfc_sealed = ChaCha20Poly1305(rfc_key).encrypt(rfc_nonce, rfc_pt, rfc_aad)
assert rfc_sealed[-16:].hex() == "1ae10b594f09e26a7e902ecbd0600691", rfc_sealed[-16:].hex()
# RFC 8439 section 2.5.2 (Poly1305)
p_key = bytes.fromhex("85d6be7857556d337f4452fe42d506a80103808afb0db2fd4abff6af4149f51b")
p_msg = b"Cryptographic Forum Research Group"
assert poly(p_key, p_msg).hex() == "a8061dc1305136c6c22b8baf0c0127a9"

rng = random.Random(8439)
def rb(n):
    return bytes(rng.randrange(256) for _ in range(n))

out = []
def kc(name, expr, want):
    out.append(f'  kcase("{name}", {expr}, "{want}") <>')

def hexof(expr):
    return f"S.hex_of({expr})"

# the RFC 8439 cases
kc("rfc8439-2.8.2", hexof(f"aead_seal({lst(rfc_key)}, {lst(rfc_nonce)}, {lst(rfc_aad)}, {lst(rfc_pt)})"),
   rfc_sealed.hex())
kc("rfc8439-2.5.2", hexof(f"poly1305_tag(A.ae.take(16n, {lst(p_key)}), A.ae.drop(16n, {lst(p_key)}), {lst(p_msg)})"),
   poly(p_key, p_msg).hex())
# the block function against the cryptography keystream
for i, counter in enumerate([0, 1, 7]):
    key = rb(32); nonce = rb(12)
    kc(f"block-{i}", hexof(f"chacha20_block({lst(key)}, {counter}, {lst(nonce)})"),
       keystream(key, counter, nonce, 64).hex())
# Poly1305 on random keys and lengths around the block size
for n in [0, 1, 15, 16, 17, 31, 32, 33, 64, 100]:
    key = rb(32); msg = rb(n)
    r, s = key[:16], key[16:]
    kc(f"poly-{n}", hexof(f"poly1305_tag(A.ae.take(16n, {lst(key)}), A.ae.drop(16n, {lst(key)}), {lst(msg)})"),
       poly(key, msg).hex())
# seal on random inputs
for i, (alen, plen) in enumerate([(0, 0), (0, 1), (13, 64), (16, 65), (5, 100), (20, 300)]):
    key = rb(32); nonce = rb(12); aad = rb(alen); pt = rb(plen)
    sealed = ChaCha20Poly1305(key).encrypt(nonce, pt, aad)
    kc(f"seal-{i}", hexof(f"aead_seal({lst(key)}, {lst(nonce)}, {lst(aad)}, {lst(pt)})"), sealed.hex())
    # open of the same sealed text gives the plaintext back
    kc(f"open-{i}", f"S.hex_of(opt(aead_open({lst(key)}, {lst(nonce)}, {lst(aad)}, {lst(sealed)})))",
       pt.hex())
# a changed tag and a changed ciphertext byte are refused
key = rb(32); nonce = rb(12); aad = rb(7); pt = rb(40)
sealed = ChaCha20Poly1305(key).encrypt(nonce, pt, aad)
bad_tag = sealed[:-1] + bytes([sealed[-1] ^ 1])
bad_ct = bytes([sealed[0] ^ 0x80]) + sealed[1:]
kc("open-bad-tag", f"S.hex_of(opt(aead_open({lst(key)}, {lst(nonce)}, {lst(aad)}, {lst(bad_tag)})))", "")
kc("open-bad-ct", f"S.hex_of(opt(aead_open({lst(key)}, {lst(nonce)}, {lst(aad)}, {lst(bad_ct)})))", "")

src = '''# aead_tests.bend: ChaCha20-Poly1305 cases (generated by gen_aead_tests.py).
#   bend aead_tests.bend

import Base
import ./sha256.bend as S
import ./chacha20.bend as C
import ./aead.bend as A

type Case is Data:
  Case{name: String, got: String, want: String}

def kcase(name: String, +got: String, want: String) -> Case:
  Case{name, got, want}

# the plaintext of an open, as hex: "" when the tag is refused (see below)
def opt(r: Maybe<&2, List<&2, U32>>) -> List<&2, U32>:
  match r:
    case Some{x}:
      x
    case None{}:
      Nil{}

def chacha20_block(key: List<&2, U32>, counter: U32, nonce: List<&2, U32>) -> List<&2, U32>:
  C.chacha20_block(key, counter, nonce)

def poly1305_tag(r16: List<&2, U32>, s16: List<&2, U32>, msg: List<&2, U32>) -> List<&2, U32>:
  A.poly1305_tag(r16, s16, msg)

def aead_seal(key: List<&2, U32>, nonce: List<&2, U32>, aad: List<&2, U32>, pt: List<&2, U32>) -> List<&2, U32>:
  A.aead_seal(key, nonce, aad, pt)

def aead_open(key: List<&2, U32>, nonce: List<&2, U32>, aad: List<&2, U32>, sealed: List<&2, U32>) -> Maybe<&2, List<&2, U32>>:
  A.aead_open(key, nonce, aad, sealed)

def cases() -> List<&2, Case>:
''' + "\n".join(out) + '''
  Nil{}

def fails.at(+c: Case, +rest: List<&2, String>) -> List<&2, String>:
  match c:
    case Case{n, +g, +w}:
      Bool.pick(List<&2, String>, String.eq(g, w), rest,
        ("FAIL " ++ n ++ "\\n  got:  " ++ g ++ "\\n  want: " ++ w) <> rest)

def fails(cs: List<&2, Case>) -> List<&2, String>:
  match cs:
    case Nil{}:
      Nil{}
    case +c <> t:
      fails.at(c, fails(t))

def main() -> IO(Unit):
  +cs = cases()
  +n = List.length(&2, Case, cs)
  +fs = fails(cs)
  +f = List.length(&2, String, fs)
  do IO<Unit>:
    List.for_each(~&2, ~String, ~IO.print, fs)
    IO.print("aead: " ++ Nat.show(Nat.sub(n, f)) ++ " passed, " ++ Nat.show(f) ++ " failed")
'''
open('aead_tests.bend', 'w').write(src)
print(len(out), "cases")
