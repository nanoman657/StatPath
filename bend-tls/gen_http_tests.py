# Writes http_tests.bend (the URL and reply parsing of http.bend) and http_fetch.bend (three
# requests to a local server, e2e/http_test.py): expected values are written here by hand from
# the HTTP and URL rules, not computed by the code under test.
#   python3 -I gen_http_tests.py
def lst(s):
    return "[" + ", ".join(str(b) for b in s.encode()) + "]"

def show_url(u):
    return f"{u[0]}|{u[1]}|{u[2]}"

cases = [
    ("url-ip-port-path", "http://127.0.0.1:4480/crl.der", ("127.0.0.1", 4480, "/crl.der")),
    ("url-no-port", "http://10.0.0.5/x/y.crl", ("10.0.0.5", 80, "/x/y.crl")),
    ("url-no-path", "http://10.0.0.5:8080", ("10.0.0.5", 8080, "/")),
    ("url-bare", "http://1.2.3.4", ("1.2.3.4", 80, "/")),
]
out = []
for name, url, want in cases:
    out.append(f'  kcase("{name}", show_url(H.http.url({lst(url)})), "{show_url(want)}") <>')
# not an IP address (a host name): refused, as the kit has no DNS
out.append('  kcase("url-host-name-refused", show_url(H.http.url(' + lst("http://example.test/x") + ')), "none") <>')
out.append('  kcase("url-https-refused", show_url(H.http.url(' + lst("https://10.0.0.5/x") + ')), "none") <>')

def lst_bytes(b):
    return "[" + ", ".join(str(x) for x in b) + "]"
replies = [
    ("reply-200-body", b"HTTP/1.0 200 OK\r\nContent-Length: 6\r\n\r\nCRLDER", "body CRLDER"),
    ("reply-404-none", b"HTTP/1.0 404 Not Found\r\n\r\nnope", "none"),
]
for name, raw, want in replies:
    out.append(f'  kcase("{name}", show_reply(H.http.reply({lst_bytes(raw)})), "{want}") <>')
src = r'''# http_tests.bend: the URL and reply parsing of http.bend (generated by gen_http_tests.py).
#   bend http_tests.bend

import Base
import ./http.bend as H

type Case is Data:
  Case{name: String, got: String, want: String}

def kcase(name: String, +got: String, want: String) -> Case:
  Case{name, got, want}

# a reply body as text, or none
def show_reply(m: Maybe<&2, List<&2, U32>>) -> String:
  match m:
    case Some{+body}:
      "body " ++ H.http.ip_str(body)
    case None{}:
      "none"

# a parsed URL as text: the address, the port and the path, or none
def show_url(m: Maybe<&2, H.Url>) -> String:
  match m:
    case Some{+u}:
      match u:
        case H.Url{+ip, +port, +path}:
          H.http.ip_str(ip) ++ "|" ++ Nat.show(port) ++ "|" ++ H.http.ip_str(path)
    case None{}:
      "none"

def cases() -> List<&2, Case>:
''' + "\n".join(out) + r'''
  Nil{}

def fails.at(+c: Case, +rest: List<&2, String>) -> List<&2, String>:
  match c:
    case Case{n, +g, +w}:
      Bool.pick(List<&2, String>, String.eq(g, w), rest,
        ("FAIL " ++ n ++ "\n  got:  " ++ g ++ "\n  want: " ++ w) <> rest)

def fails(cs: List<&2, Case>) -> List<&2, String>:
  match cs:
    case Nil{}:
      Nil{}
    case +c <> t:
      fails.at(c, fails(t))

def main() -> IO(Unit):
  +cs = cases()
  +n = List.length(&2, Case, cs)
  +fs = fails(cs)
  +f = List.length(&2, String, fs)
  do IO<Unit>:
    List.for_each(~&2, ~String, ~IO.print, fs)
    IO.print("http-url: " ++ Nat.show(Nat.sub(n, f)) ++ " passed, " ++ Nat.show(f) ++ " failed")
'''
src = src.replace("def show_url(m: Maybe<&2, H.Url>)", "def show_url(m: Maybe<&2, H.Url>)")
open("http_tests.bend", "w").write(src)
print(len(out), "cases")

fetch = r'''# http_fetch.bend: three requests to a local server (e2e/http_test.py serves them on port 4480).
import Base
import ./http.bend as H

def show_reply(m: Maybe<&2, List<&2, U32>>) -> String:
  match m:
    case Some{+body}:
      "body " ++ H.http.ip_str(body)
    case None{}:
      "no body"

def main() -> IO(Unit):
  do IO<Unit>:
    get : Maybe<&2, List<&2, U32>> <- H.http.get_url("http://127.0.0.1:4480/crl.der")
    IO.print("get: " ++ show_reply(get) ++ "\n")
    missing : Maybe<&2, List<&2, U32>> <- H.http.get_url("http://127.0.0.1:4480/missing")
    IO.print("missing: " ++ show_reply(missing) ++ "\n")
    echo : Maybe<&2, List<&2, U32>> <- H.http.post_url("http://127.0.0.1:4480/echo", "application/ocsp-request", H.http.b("ping-body"))
    IO.print("echo: " ++ show_reply(echo) ++ "\n")
'''
open("http_fetch.bend", "w").write(fetch)
print("fetch written")
