# Writes rsa_sig_tests.bend: RSA-PSS and RSA-PKCS1 v1.5 (SHA-256) verification
# against signatures made by the cryptography package. Each valid signature
# must verify; a changed message or a changed signature must not.
#   python3 -I gen_rsa_sig_tests.py
import random
from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.asymmetric import rsa as crsa, padding

def lst(xs):
    return "[" + ", ".join(str(x) for x in xs) + "]"

rng = random.Random(4)
out = []
for bits in [2048, 1024]:
    key = crsa.generate_private_key(public_exponent=65537, key_size=bits)
    n = key.public_key().public_numbers().n
    k = (n.bit_length() + 7) // 8
    nb = list(n.to_bytes(k, "big"))
    for i in range(2):
        msg = bytes(rng.randrange(256) for _ in range(rng.randrange(0, 90)))
        pss = key.sign(msg, padding.PSS(mgf=padding.MGF1(hashes.SHA256()), salt_length=32), hashes.SHA256())
        pk1 = key.sign(msg, padding.PKCS1v15(), hashes.SHA256())
        # verification must agree with cryptography's own check (it raises on failure)
        key.public_key().verify(pss, msg, padding.PSS(mgf=padding.MGF1(hashes.SHA256()), salt_length=32), hashes.SHA256())
        key.public_key().verify(pk1, msg, padding.PKCS1v15(), hashes.SHA256())
        bad = bytes([msg[0] ^ 1]) + msg[1:] if msg else b"x"
        badsig = bytes([pss[0] ^ 0x40]) + pss[1:]
        badsig1 = bytes([pk1[-1] ^ 1]) + pk1[1:]
        ml = lst(list(msg)); bl = lst(list(bad)); sl = lst(list(pss)); s1 = lst(list(pk1))
        nl = lst(nb); bsl = lst(list(badsig)); bs1 = lst(list(badsig1))
        out += [
            f'  kcase("pss-{bits}-{i}", S.bool_show(R.rsa.verify_pss({nl}, {sl}, {ml})), "True") <>',
            f'  kcase("pss-{bits}-{i}-wrong-msg", S.bool_show(R.rsa.verify_pss({nl}, {sl}, {bl})), "False") <>',
            f'  kcase("pss-{bits}-{i}-bad-sig", S.bool_show(R.rsa.verify_pss({nl}, {bsl}, {ml})), "False") <>',
            f'  kcase("pkcs1-{bits}-{i}", S.bool_show(R.rsa.verify_pkcs1({nl}, {s1}, {ml})), "True") <>',
            f'  kcase("pkcs1-{bits}-{i}-wrong-msg", S.bool_show(R.rsa.verify_pkcs1({nl}, {s1}, {bl})), "False") <>',
            f'  kcase("pkcs1-{bits}-{i}-bad-sig", S.bool_show(R.rsa.verify_pkcs1({nl}, {bs1}, {ml})), "False") <>',
        ]

src = '''# rsa_sig_tests.bend: PSS and PKCS#1 v1.5 verification (generated by
# gen_rsa_sig_tests.py). Each valid signature verifies; altered ones do not.
#   bend rsa_sig_tests.bend

import Base
import ./sha256.bend as S
import ./rsa.bend as R

type Case is Data:
  Case{name: String, got: String, want: String}

def kcase(name: String, +got: String, want: String) -> Case:
  Case{name, got, want}

def cases() -> List<&2, Case>:
''' + "\n".join(out) + '''
  Nil{}

def fails.at(+c: Case, +rest: List<&2, String>) -> List<&2, String>:
  match c:
    case Case{n, +g, +w}:
      Bool.pick(List<&2, String>, String.eq(g, w), rest,
        ("FAIL " ++ n ++ "\\n  got:  " ++ g ++ "\\n  want: " ++ w) <> rest)

def fails(cs: List<&2, Case>) -> List<&2, String>:
  match cs:
    case Nil{}:
      Nil{}
    case +c <> t:
      fails.at(c, fails(t))

def main() -> IO(Unit):
  +cs = cases()
  +n = List.length(&2, Case, cs)
  +fs = fails(cs)
  +f = List.length(&2, String, fs)
  do IO<Unit>:
    List.for_each(~&2, ~String, ~IO.print, fs)
    IO.print("rsa-sig: " ++ Nat.show(Nat.sub(n, f)) ++ " passed, " ++ Nat.show(f) ++ " failed")
'''
src = src.replace("S.bool_show(", "Bool.show(")
open("rsa_sig_tests.bend", "w").write(src)
print(len(out), "cases")
