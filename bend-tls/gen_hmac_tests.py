# Writes hmac_tests.bend: RFC 4231 vectors and key-length boundaries.
# Every expected value is checked against the RFC's printed digest (for the
# RFC cases) or Python's hmac module (for the boundary cases).
#   python3 -I gen_hmac_tests.py
import hmac, hashlib, random

RFC = {  # RFC 4231 test case -> the digest printed in the RFC
    1: "b0344c61d8db38535ca8afceaf0bf12b881dc200c9833da726e9376c2e32cff7",
    2: "5bdcc146bf60754e6a042426089575c75a003f089d2739839dec58b964ec3843",
    3: "773ea91e36800e46854db8ebd09181a72959098b3ef8c122d9635514ced565fe",
    6: "60e431591ee0b67f0d8a26aacbf5b77f8e0bc6213728c5140546040f0ee37f54",
}

def rfc_case(n):
    if n == 1:
        return bytes([0x0b] * 20), b"Hi There"
    if n == 2:
        return b"Jefe", b"what do ya want for nothing?"
    if n == 3:
        return bytes([0xaa] * 20), bytes([0xdd] * 50)
    if n == 6:
        return bytes([0xaa] * 131), b"Test Using Larger Than Block-Size Key - Hash Key First"

random.seed(4231)
cases = []
for n in sorted(RFC):
    key, msg = rfc_case(n)
    want = hmac.new(key, msg, hashlib.sha256).hexdigest()
    assert want == RFC[n], (n, want)  # Python agrees with the RFC
    cases.append((f"rfc4231-{n}", key, msg, want))
for klen in [0, 1, 63, 64, 65, 200]:
    key = bytes(random.randrange(256) for _ in range(klen))
    msg = bytes(random.randrange(256) for _ in range(77))
    cases.append((f"key-{klen}", key, msg, hmac.new(key, msg, hashlib.sha256).hexdigest()))

def lst(b):
    return "[" + ", ".join(str(x) for x in b) + "]"

body = []
for name, key, msg, want in cases:
    body.append(f'  hcase("{name}", {lst(key)}, {lst(msg)}, "{want}") <>')

src = f'''# hmac_tests.bend: HMAC-SHA256 cases (generated by gen_hmac_tests.py).
#   bend hmac_tests.bend

import Base
import ./hmac.bend as H

type Case is Data:
  Case{{name: String, got: String, want: String}}

def hcase(name: String, +key: List<&2, U32>, +msg: List<&2, U32>, want: String) -> Case:
  Case{{name, H.hmac_hex(key, msg), want}}

def cases() -> List<&2, Case>:
{chr(10).join(body)}
  Nil{{}}

def fails.put(n: String, +g: String, +w: String, +rest: List<&2, String>) -> List<&2, String>:
  Bool.pick(List<&2, String>, String.eq(g, w), rest,
    ("FAIL " ++ n ++ "\\n  got:  " ++ g ++ "\\n  want: " ++ w) <> rest)

def fails.at(+c: Case, rest: List<&2, String>) -> List<&2, String>:
  match c:
    case Case{{n, +g, +w}}:
      fails.put(n, g, w, rest)

def fails(cs: List<&2, Case>) -> List<&2, String>:
  match cs:
    case Nil{{}}:
      Nil{{}}
    case +c <> t:
      fails.at(c, fails(t))

def main() -> IO(Unit):
  +cs = cases()
  +n = List.length(&2, Case, cs)
  +fs = fails(cs)
  +f = List.length(&2, String, fs)
  do IO<Unit>:
    List.for_each(~&2, ~String, ~IO.print, fs)
    IO.print("hmac-sha256: " ++ Nat.show(Nat.sub(n, f)) ++ " passed, " ++ Nat.show(f) ++ " failed")
'''
open('hmac_tests.bend','w').write(src)
print(len(cases), "cases")
