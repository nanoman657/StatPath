# Writes x25519_tests.bend: X25519 against the cryptography package, plus the
# RFC 7748 section 5.2 vector and the section 6.1 Alice/Bob exchange (each
# checked against cryptography before it is written out).
#   python3 -I gen_x25519_tests.py
import random
from cryptography.hazmat.primitives.asymmetric.x25519 import X25519PrivateKey, X25519PublicKey

def x25519(k, u):
    return X25519PrivateKey.from_private_bytes(k).exchange(X25519PublicKey.from_public_bytes(u))

def lst(b):
    return "[" + ", ".join(str(x) for x in b) + "]"

rfc_k = bytes.fromhex("a546e36bf0527c9d3b16154b82465edd62144c0ac1fc5a18506a2244ba449ac4")
rfc_u = bytes.fromhex("e6db6867583030db3594c1a424b15f7c726624ec26b3353b10a903a6d0ab1c4c")
assert x25519(rfc_k, rfc_u).hex() == "c3da55379de9c6908e94ea4df28d084f32eccf03491c71f754b4075577a28552"

a_priv = bytes.fromhex("77076d0a7318a57d3c16c17251b26645df4c2f87ebc0992ab177fba51db92c2a")
a_pub = bytes.fromhex("8520f0098930a754748b7ddcb43ef75a0dbf3a0d26381af4eba4a98eaa9b4e6a")
b_priv = bytes.fromhex("5dab087e624a8a4b79e17f8b83800ee66f3bb1292618b6fd1c2f8b27ff88e0eb")
b_pub = bytes.fromhex("de9edb7d7b7dc1b4d35b61c2ece435373f8343c85b78674dadfc7e146f882b4f")
shared = bytes.fromhex("4a5d9d5ba4ce2de1728e3bf480350f25e07e21c947d19e3376f09b3c1e161742")
# the public keys are the base point (u = 9) times the private keys
base = (9).to_bytes(1, "little") + bytes(31)
assert x25519(a_priv, base) == a_pub and x25519(b_priv, base) == b_pub
assert x25519(a_priv, b_pub) == shared and x25519(b_priv, a_pub) == shared

rng = random.Random(7748)
cases = [
    ("rfc7748-5.2", rfc_k, rfc_u),
    ("rfc7748-6.1-alice-pub", a_priv, base),
    ("rfc7748-6.1-shared", a_priv, b_pub),
]
for i in range(4):
    cases.append((f"random-{i}", bytes(rng.randrange(256) for _ in range(32)),
                  bytes(rng.randrange(256) for _ in range(32))))

out = []
for name, k, u in cases:
    want = x25519(k, u).hex()
    out.append(f'  kcase("{name}", S.hex_of(x25519({lst(k)}, {lst(u)})), "{want}") <>')

src = '''# x25519_tests.bend: X25519 cases (generated by gen_x25519_tests.py).
#   bend x25519_tests.bend

import Base
import ./sha256.bend as S
import ./x25519.bend as X

type Case is Data:
  Case{name: String, got: String, want: String}

def kcase(name: String, +got: String, want: String) -> Case:
  Case{name, got, want}

def cases() -> List<&2, Case>:
''' + "\n".join(out) + '''
  Nil{}

def fails.at(+c: Case, +rest: List<&2, String>) -> List<&2, String>:
  match c:
    case Case{n, +g, +w}:
      Bool.pick(List<&2, String>, String.eq(g, w), rest,
        ("FAIL " ++ n ++ "\\n  got:  " ++ g ++ "\\n  want: " ++ w) <> rest)

def fails(cs: List<&2, Case>) -> List<&2, String>:
  match cs:
    case Nil{}:
      Nil{}
    case +c <> t:
      fails.at(c, fails(t))

def main() -> IO(Unit):
  +cs = cases()
  +n = List.length(&2, Case, cs)
  +fs = fails(cs)
  +f = List.length(&2, String, fs)
  do IO<Unit>:
    List.for_each(~&2, ~String, ~IO.print, fs)
    IO.print("x25519: " ++ Nat.show(Nat.sub(n, f)) ++ " passed, " ++ Nat.show(f) ++ " failed")
'''
src = src.replace("x25519(", "X.x25519(")
open("x25519_tests.bend", "w").write(src)
print(len(out), "cases")
