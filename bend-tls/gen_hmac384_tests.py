# Writes hmac384_tests.bend: HMAC-SHA-384 against Python's hmac module, with key lengths
# on both sides of the 128-byte block (a key longer than the block is hashed first) and
# the RFC 4231 test cases 1 and 2 for SHA-384.
#   python3 -I gen_hmac384_tests.py
import hashlib
import hmac
import random

def lst(b):
    return "[" + ", ".join(str(x) for x in b) + "]"

rng = random.Random(4384)
def rb(n):
    return bytes(rng.randrange(256) for _ in range(n))

# RFC 4231 test cases 1 and 2 (SHA-384)
assert hmac.new(bytes([0x0b] * 20), b"Hi There", hashlib.sha384).hexdigest() == \
    "afd03944d84895626b0825f4ab46907f15f9dadbe4101ec682aa034c7cebc59cfaea9ea9076ede7f4af152e8b2fa9cb6"
assert hmac.new(b"Jefe", b"what do ya want for nothing?", hashlib.sha384).hexdigest() == \
    "af45d2e376484031617f78d2b58a6b1b9c7ef464f5a01b47e42ec3736322445e8e2240ca5e69e2c78b3239ecfab21649"

out = []
def kc(name, key, msg):
    want = hmac.new(key, msg, hashlib.sha384).hexdigest()
    out.append(f'  kcase("{name}", S.hex_of(H3.hmac384({lst(key)}, {lst(msg)})), "{want}") <>')

kc("rfc4231-1", bytes([0x0b] * 20), b"Hi There")
kc("rfc4231-2", b"Jefe", b"what do ya want for nothing?")
for klen in [0, 1, 47, 48, 127, 128, 129, 200]:
    for mlen in [0, 1, 111, 128, 300]:
        kc(f"key{klen}-msg{mlen}", rb(klen), rb(mlen))

src = r'''# hmac384_tests.bend: HMAC-SHA-384 (generated by gen_hmac384_tests.py).
#   bend hmac384_tests.bend

import Base
import ./sha256.bend as S
import ./hmac384.bend as H3

type Case is Data:
  Case{name: String, got: String, want: String}

def kcase(name: String, +got: String, want: String) -> Case:
  Case{name, got, want}

def cases() -> List<&2, Case>:
''' + "\n".join(out) + r'''
  Nil{}

def fails.at(+c: Case, +rest: List<&2, String>) -> List<&2, String>:
  match c:
    case Case{n, +g, +w}:
      Bool.pick(List<&2, String>, String.eq(g, w), rest,
        ("FAIL " ++ n ++ "\n  got:  " ++ g ++ "\n  want: " ++ w) <> rest)

def fails(cs: List<&2, Case>) -> List<&2, String>:
  match cs:
    case Nil{}:
      Nil{}
    case +c <> t:
      fails.at(c, fails(t))

def main() -> IO(Unit):
  +cs = cases()
  +n = List.length(&2, Case, cs)
  +fs = fails(cs)
  +f = List.length(&2, String, fs)
  do IO<Unit>:
    List.for_each(~&2, ~String, ~IO.print, fs)
    IO.print("hmac-sha384: " ++ Nat.show(Nat.sub(n, f)) ++ " passed, " ++ Nat.show(f) ++ " failed")
'''
open("hmac384_tests.bend", "w").write(src)
print(len(out), "cases")
