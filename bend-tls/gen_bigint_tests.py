# Writes bigint_tests.bend: Montgomery products and the limb helpers, against
# Python integers. mont(a, b, m, n0, n) = a * b * 2^(-16 n) mod m, checked on
# random odd moduli of several sizes.
#   python3 -I gen_bigint_tests.py
import random

def limbs(x, length):
    out = []
    for _ in range(length):
        out.append(x & 0xffff)
        x >>= 16
    assert x == 0
    return out

def lst(xs):
    return "[" + ", ".join(f"{x}n" for x in xs) + "]"

def text(xs):
    return ",".join(str(x) for x in xs) + ","

rng = random.Random(16)
cases = []
for n in [1, 2, 4, 8, 16]:
    for rep in range(2):
        m = rng.randrange(1, 1 << (16 * n)) | 1
        m |= 1 << (16 * n - 1)  # full length
        a = rng.randrange(m); b = rng.randrange(m)
        R = 1 << (16 * n)
        want = (a * b * pow(R, -1, m)) % m
        n0 = (-pow(m & 0xffff, -1, 65536)) % 65536
        cases.append((f"mont-n{n}-{rep}", a, b, m, n0, n, want))

# n0 check: m0 * n0 = -1 (mod 2^16)
out = []
for name, a, b, m, n0, n, want in cases:
    assert ((m & 0xffff) * n0) % 65536 == 65535
    L = n + 2
    out.append(f'  kcase("{name}", limbs_text(B.bi.mont({lst(limbs(a, L))}, {lst(limbs(b, L))}, {lst(limbs(m, L))}, {n0}n, {n}n), ""), "{text(limbs(want, L))}") <>')


SRC_TEMPLATE_START = 0
src = '''# bigint_tests.bend: Montgomery products against Python integers
# (generated by gen_bigint_tests.py). The expected value is the limb list.
#   bend bigint_tests.bend

import Base
import ./bigint.bend as B

type Case is Data:
  Case{name: String, got: String, want: String}

def kcase(name: String, +got: String, want: String) -> Case:
  Case{name, got, want}

# the limbs as text, least significant first, each followed by a comma
def limbs_text(xs: List<&2, Nat>, acc: String) -> String:
  match xs:
    case Nil{}:
      acc
    case x <> t:
      limbs_text(t, acc ++ Nat.show(x) ++ ",")

def cases() -> List<&2, Case>:
''' + "\n".join(out) + '''
  Nil{}

def fails.at(+c: Case, +rest: List<&2, String>) -> List<&2, String>:
  match c:
    case Case{n, +g, +w}:
      Bool.pick(List<&2, String>, String.eq(g, w), rest,
        ("FAIL " ++ n ++ "\\n  got:  " ++ g ++ "\\n  want: " ++ w) <> rest)

def fails(cs: List<&2, Case>) -> List<&2, String>:
  match cs:
    case Nil{}:
      Nil{}
    case +c <> t:
      fails.at(c, fails(t))

def main() -> IO(Unit):
  +cs = cases()
  +n = List.length(&2, Case, cs)
  +fs = fails(cs)
  +f = List.length(&2, String, fs)
  do IO<Unit>:
    List.for_each(~&2, ~String, ~IO.print, fs)
    IO.print("bigint: " ++ Nat.show(Nat.sub(n, f)) ++ " passed, " ++ Nat.show(f) ++ " failed")
'''

open("bigint_tests.bend", "w").write(src)
print(len(cases), "cases")
