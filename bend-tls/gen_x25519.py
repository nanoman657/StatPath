# Writes x25519.bend: X25519 (RFC 7748). A field element is sixteen 16-bit Nat
# limbs, least significant first; arithmetic is modulo p = 2^255 - 19. The
# product, the carry chains and the byte packing are generated here, one
# operation per line. Bend source text is assembled with plain substitution,
# so its braces stay literal.
#   python3 -I gen_x25519.py
N = 16
cnt = [0]
ops = []

def let(expr):
    cnt[0] += 1
    v = f"q{cnt[0]}"
    ops.append(f"  +{v} = ({expr} : Nat)")
    return v

def take_ops():
    text = "\n".join(ops)
    ops.clear()
    return text

def names(p):
    return [f"{p}{i}" for i in range(N)]

def pat(p):
    return ", ".join(f"+{p}{i}" for i in range(N))

def fe_ctor(vals):
    return ", ".join(vals)

# schoolbook product; limbs i+j >= 16 fold back with 2^256 = 38 (mod p)
raw = []
for k in range(N):
    terms = [f"a{i} * b{j}" for i in range(N) for j in range(N) if i + j == k]
    high = [f"a{i} * b{j}" for i in range(N) for j in range(N) if i + j == k + N]
    expr = " + ".join(terms)
    if high:
        expr += " + 38n * (" + " + ".join(high) + ")"
    raw.append(let(expr))
MUL_OPS = take_ops()

def carry(e, wrap):
    out = []
    carry_ = None
    for k in range(N):
        cur = e[k] if carry_ is None else let(f"{e[k]} + {carry_}")
        c = let(f"{cur} / 65536n")
        out.append(let(f"{cur} % 65536n"))
        carry_ = c
    if wrap:
        out[0] = let(f"{out[0]} + 38n * {carry_}")
    return out, carry_

pass_out, _ = carry(names("x"), wrap=True)
PASS_OPS = take_ops()
nw_out, nw_top = carry(names("x"), wrap=False)
NW_OPS = take_ops()

# the 32 little-endian bytes of a canonical field element
byte_vals = []
for i in range(N):
    byte_vals.append(f"Nat.mod(x{i}, 256n)")
    byte_vals.append(f"Nat.div(x{i}, 256n)")
BYTES_EXPR = " <> ".join(byte_vals) + " <> Nil{}"

of_bytes_pat = " <> ".join(f"b{i}" for i in range(32)) + " <> Nil{}"
of_bytes_vals = ", ".join(
    f"(b{2 * i} + Nat.mul(256n, b{2 * i + 1}) : Nat)" if i < N - 1
    else f"(b{2 * i} + Nat.mul(256n, Nat.mod(b{2 * i + 1}, 128n)) : Nat)"
    for i in range(N))

TEMPLATE = r"""# x25519.bend: X25519 (RFC 7748). A field element is sixteen 16-bit Nat limbs,
# least significant first; arithmetic is modulo p = 2^255 - 19. The product
# and the carry chains are generated by gen_x25519.py. Scalars and coordinates
# are 32-byte lists of U32 values 0..255, little-endian as RFC 7748 defines.

import Base

type FE is Data:
  FE{ZFIELDS}

def fe.zero() -> FE:
  FE{ZEROS}

def fe.one() -> FE:
  FE{ONES}

def fe.add(+a: FE, +b: FE) -> FE:
  match a:
    case FE{APAT}:
      match b:
        case FE{BPAT}:
          FE{ADDS}

# a - b, with 2p added to every limb so none goes negative (b's limbs are below 2^17)
def fe.sub(+a: FE, +b: FE) -> FE:
  match a:
    case FE{APAT}:
      match b:
        case FE{BPAT}:
          FE{SUBS}

# one carry pass; the top carry wraps into limb 0 times 38
def fe.pass(+x: FE) -> FE:
  match x:
    case FE{XPAT}:
PASS_OPS_IND
      FE{PASS_RES}

def fe.norm(+x: FE) -> FE:
  fe.pass(fe.pass(x))

# a * b mod p
def fe.mul(+a: FE, +b: FE) -> FE:
  match a:
    case FE{APAT}:
      match b:
        case FE{BPAT}:
MUL_OPS_IND
          fe.norm(FE{MUL_RES})

def fe.sq(+a: FE) -> FE:
  fe.mul(a, a)

# k * x for a small constant k (the ladder uses 121665)
def fe.mul_small(+x: FE, k: Nat) -> FE:
  fe.mul(x, FE{SMALL_ONES})

# one carry pass without the wrap: limbs below 2^16 and the carry out of limb 15
def fe.carrynw(+x: FE) -> FE & Nat:
  match x:
    case FE{XPAT}:
NW_OPS_IND
      (FE{NW_RES}, NW_TOP)

def fe.addl0(+x: FE, +c: Nat) -> FE:
  match x:
    case FE{XPAT}:
      FE{ADDL0_RES}

# bit 255 of x, and x with bit 255 cleared
def fe.hi255(+x: FE) -> Nat:
  match x:
    case FE{XPAT}:
      Nat.div(x15, 32768n)

def fe.low255(+x: FE) -> FE:
  match x:
    case FE{XPAT}:
      FE{LOW_RES}

# x (limbs exact, value below 2^256) reduced once: fold bit 255 as 19
def fe.cA(+y: FE) -> FE:
  fe.cA2(fe.carrynw(fe.addl0(fe.low255(y), Nat.mul(19n, fe.hi255(y)))))

def fe.cA2(r: FE & Nat) -> FE:
  (w, t) = r
  fe.cB(w)

# w below 2^255 + 19: subtract p when w + 19 reaches 2^255
def fe.cB(+w: FE) -> FE:
  fe.cB2(w, fe.carrynw(fe.addl0(w, 19n)))

def fe.cB2(+w: FE, g: FE & Nat) -> FE:
  (+gg, t) = g
  fe.cB3(w, fe.hi255(gg), gg)

def fe.cB3(+w: FE, h: Nat, +gg: FE) -> FE:
  match h:
    case 0n:
      w
    case 1n+_:
      fe.low255(gg)

# repeat the carry until the top carry is zero, so the value is below 2^256
def fe.cfold(fuel: Nat, r: FE & Nat) -> FE:
  match fuel:
    case 0n:
      fe.zero()
    case 1n+p:
      (y, +t) = r
      match t:
        case 0n:
          fe.cA(y)
        case 1n+_:
          fe.cfold(p, fe.carrynw(fe.addl0(y, Nat.mul(38n, t))))

# x mod p, canonical: limbs below 2^16 and the value below p
def fe.canon(+x: FE) -> FE:
  fe.cfold(4n, fe.carrynw(fe.norm(x)))

# the 32 little-endian bytes of x (x canonical)
def fe.bytes(+x: FE) -> List<&2, Nat>:
  match x:
    case FE{XPAT}:
      BYTES_EXPR_IND

# the field element of 32 little-endian bytes (bit 255 is ignored)
def fe.of_bytes(b: List<&2, Nat>) -> FE:
  match b:
    case OF_BYTES_PAT:
      FE{OF_BYTES_VALS}
    case _:
      fe.zero()

# z^e square-and-multiply, bits of e most significant first
def fe.pow(bits: List<&2, Nat>, +x: FE, +r: FE) -> FE:
  match bits:
    case Nil{}:
      r
    case b <> t:
      fe.pow(t, x, fe.pow.step(b, x, fe.sq(r)))

def fe.pow.step(b: Nat, +x: FE, +r2: FE) -> FE:
  match b:
    case 0n:
      r2
    case 1n+_:
      fe.mul(r2, x)

# 1/z = z^(p-2)
def fe.inv(+z: FE) -> FE:
  fe.pow(P2_BITS, z, fe.one())

def fe.pick(s: Nat, +a: FE, +b: FE) -> FE:
  match s:
    case 0n:
      a
    case 1n+_:
      b

# the Montgomery ladder state: x2, z2, x3, z3, and the swap bit
type LS is Data:
  LS{x2: FE, z2: FE, x3: FE, z3: FE, swap: Nat}

# one ladder step for scalar bit b (RFC 7748 section 5)
def ladder.step(+b: Nat, +st: LS, +u: FE) -> LS:
  match st:
    case LS{+x2, +z2, +x3, +z3, +swap}:
      LADDER_OPS_IND

def ladder(bits: List<&2, Nat>, +st: LS, +u: FE) -> LS:
  match bits:
    case Nil{}:
      st
    case b <> t:
      ladder(t, ladder.step(b, st, u), u)

# the scalar with the RFC 7748 clamping, as a 255-bit list, most significant first
def x25519.clamp(k: List<&2, U32>) -> List<&2, U32>:
  match k:
    case k0 <> k1 <> k2 <> k3 <> k4 <> k5 <> k6 <> k7 <> k8 <> k9 <> k10 <> k11 <> k12 <> k13 <> k14 <> k15 <> k16 <> k17 <> k18 <> k19 <> k20 <> k21 <> k22 <> k23 <> k24 <> k25 <> k26 <> k27 <> k28 <> k29 <> k30 <> k31 <> Nil{}:
      U32.and(k0, 248) <> k1 <> k2 <> k3 <> k4 <> k5 <> k6 <> k7 <> k8 <> k9 <> k10 <> k11
        <> k12 <> k13 <> k14 <> k15 <> k16 <> k17 <> k18 <> k19 <> k20 <> k21 <> k22 <> k23
        <> k24 <> k25 <> k26 <> k27 <> k28 <> k29 <> k30 <> U32.or(U32.and(k31, 127), 64) <> Nil{}
    case _:
      Nil{}

def x25519.tonat(xs: List<&2, U32>) -> List<&2, Nat>:
  match xs:
    case Nil{}:
      Nil{}
    case x <> t:
      U32.to_nat(x) <> x25519.tonat(t)

def x25519.tou32(xs: List<&2, Nat>) -> List<&2, U32>:
  match xs:
    case Nil{}:
      Nil{}
    case x <> t:
      U32.from_nat(x) <> x25519.tou32(t)

# the bits of a byte, least significant first
def x25519.bits(k: Nat, +v: Nat) -> List<&2, Nat>:
  match k:
    case 0n:
      Nil{}
    case 1n+p:
      Nat.mod(v, 2n) <> x25519.bits(p, Nat.div(v, 2n))

def x25519.bitlist(+bs: List<&2, Nat>) -> List<&2, Nat>:
  match bs:
    case Nil{}:
      Nil{}
    case b <> t:
      List.append(&2, Nat, x25519.bits(8n, b), x25519.bitlist(t))

# the 255 scalar bits, most significant first (bit 255 is zero after clamping)
def x25519.scalar_bits(k: List<&2, U32>) -> List<&2, Nat>:
  List.reverse(&2, Nat, List.take(&2, Nat, x25519.bitlist(x25519.tonat(x25519.clamp(k))), 255n))

# X25519(k, u): the scalar k times the point with u-coordinate u, 32 bytes out
def x25519(k: List<&2, U32>, u: List<&2, U32>) -> List<&2, U32>:
  +uu = fe.of_bytes(x25519.tonat(u))
  +st = ladder(x25519.scalar_bits(k), LS{fe.one(), fe.zero(), uu, fe.one(), 0n}, uu)
  x25519.out(st)

def x25519.out(st: LS) -> List<&2, U32>:
  match st:
    case LS{+x2, +z2, +x3, +z3, +swap}:
      x25519.tou32(fe.bytes(fe.canon(fe.mul(fe.pick(swap, x2, x3), fe.inv(fe.pick(swap, z2, z3))))))
"""

def bend_list(xs):
    return ", ".join(xs)

P = 2**255 - 19
two_p_limbs = [((2 * P) >> (16 * i)) & 0xffff for i in range(N)]
ONES = ["1n"] + ["0n"] * (N - 1)
ZEROS = ["0n"] * N
ADD = [f"(a{i} + b{i} : Nat)" for i in range(N)]
SUB = [f"(a{i} + {two_p_limbs[i]}n - b{i} : Nat)" for i in range(N)]
ADDL0 = ["(x0 + c : Nat)"] + [f"x{i}" for i in range(1, N)]
LOW = [f"x{i}" for i in range(N - 1)] + ["Nat.mod(x15, 32768n)"]
SMALL = ["121665n"] + ["0n"] * (N - 1)
P2_BITS = [((P - 2) >> i) & 1 for i in range(254, -1, -1)]
# the ladder body, with the same named values as RFC 7748 section 5
LADDER = [
    "  +sw = Nat.mod(Nat.add(swap, b), 2n)",
    "  +X2 = fe.pick(sw, x2, x3)",
    "  +X3 = fe.pick(sw, x3, x2)",
    "  +Z2 = fe.pick(sw, z2, z3)",
    "  +Z3 = fe.pick(sw, z3, z2)",
    "  +A = fe.add(X2, Z2)",
    "  +AA = fe.sq(A)",
    "  +B = fe.sub(X2, Z2)",
    "  +BB = fe.sq(B)",
    "  +E = fe.sub(AA, BB)",
    "  +C = fe.add(X3, Z3)",
    "  +D = fe.sub(X3, Z3)",
    "  +DA = fe.mul(D, A)",
    "  +CB = fe.mul(C, B)",
    "  +nx3 = fe.sq(fe.add(DA, CB))",
    "  +nz3 = fe.mul(u, fe.sq(fe.sub(DA, CB)))",
    "  +nx2 = fe.mul(AA, BB)",
    "  +nz2 = fe.mul(E, fe.add(AA, fe.mul_small(E, 121665n)))",
    "  LS{nx2, nz2, nx3, nz3, b}",
]
LADDER_BODY = "\n".join(LADDER)

def indent(text, n):
    pad = " " * n
    return "\n".join(pad + ln if ln else ln for ln in text.split("\n"))

src = TEMPLATE
subs = {
    "ZFIELDS": ", ".join(f"l{i}: Nat" for i in range(N)),
    "ZEROS": fe_ctor(ZEROS),
    "ONES": fe_ctor(ONES),
    "APAT": pat("a"),
    "BPAT": pat("b"),
    "ADDS": fe_ctor(ADD),
    "SUBS": fe_ctor(SUB),
    "XPAT": pat("x"),
    "PASS_RES": fe_ctor(pass_out),
    "NW_RES": fe_ctor(nw_out),
    "NW_TOP": nw_top,
    "MUL_RES": fe_ctor(raw),
    "SMALL_ONES": "k, " + ", ".join(["0n"] * (N - 1)),
    "ADDL0_RES": fe_ctor(ADDL0),
    "LOW_RES": fe_ctor(LOW),
    "BYTES_EXPR_IND": BYTES_EXPR,
    "OF_BYTES_PAT": of_bytes_pat,
    "OF_BYTES_VALS": of_bytes_vals,
    "P2_BITS": "[" + ", ".join(str(b) for b in P2_BITS) + "]",
    "LADDER_OPS_IND": LADDER_BODY.replace("\n", "\n      ").replace("  +", "+", 0),
}
src = src.replace("P2_BITS", "P2_BITS_LIST") if False else src
for key in sorted(subs, key=len, reverse=True):
    if key == "P2_BITS":
        continue
    src = src.replace(key, subs[key])
src = src.replace("FE{" + "ZFIELDS" + "}", "")
src = src.replace("  FE{", "  FE{")
src = src.replace("PASS_OPS_IND", indent(PASS_OPS, 6))
src = src.replace("MUL_OPS_IND", indent(MUL_OPS, 8))
src = src.replace("NW_OPS_IND", indent(NW_OPS, 6))
src = src.replace("BYTES_EXPR_IND", BYTES_EXPR)

