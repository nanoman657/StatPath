# Writes rsa_tests.bend: RSAVP1 (sig^65537 mod n) against Python's pow, on
# RSA moduli made by the cryptography package (1024- and 2048-bit).
#   python3 -I gen_rsa_tests.py
import random
from cryptography.hazmat.primitives.asymmetric import rsa as crsa

def lst(xs):
    return "[" + ", ".join(str(x) for x in xs) + "]"

rng = random.Random(3)
out = []
for bits, reps in [(1024, 2), (2048, 2)]:
    for rep in range(reps):
        key = crsa.generate_private_key(public_exponent=65537, key_size=bits)
        n = key.public_key().public_numbers().n
        k = (n.bit_length() + 7) // 8
        s = rng.randrange(1, n)
        want = pow(s, 65537, n).to_bytes(k, "big")
        sb = s.to_bytes(k, "big"); nb = n.to_bytes(k, "big")
        out.append(f'  kcase("rsa{bits}-{rep}", S.hex_of(R.rsa.public({lst(sb)}, {lst(nb)})), "{want.hex()}") <>')

src = '''# rsa_tests.bend: RSAVP1 with e = 65537 against Python's pow (generated by
# gen_rsa_tests.py).
#   bend rsa_tests.bend

import Base
import ./sha256.bend as S
import ./rsa.bend as R

type Case is Data:
  Case{name: String, got: String, want: String}

def kcase(name: String, +got: String, want: String) -> Case:
  Case{name, got, want}

def cases() -> List<&2, Case>:
''' + "\n".join(out) + '''
  Nil{}

def fails.at(+c: Case, +rest: List<&2, String>) -> List<&2, String>:
  match c:
    case Case{n, +g, +w}:
      Bool.pick(List<&2, String>, String.eq(g, w), rest,
        ("FAIL " ++ n ++ "\\n  got:  " ++ g ++ "\\n  want: " ++ w) <> rest)

def fails(cs: List<&2, Case>) -> List<&2, String>:
  match cs:
    case Nil{}:
      Nil{}
    case +c <> t:
      fails.at(c, fails(t))

def main() -> IO(Unit):
  +cs = cases()
  +n = List.length(&2, Case, cs)
  +fs = fails(cs)
  +f = List.length(&2, String, fs)
  do IO<Unit>:
    List.for_each(~&2, ~String, ~IO.print, fs)
    IO.print("rsa: " ++ Nat.show(Nat.sub(n, f)) ++ " passed, " ++ Nat.show(f) ++ " failed")
'''
open("rsa_tests.bend", "w").write(src)
print(len(out), "cases")
