#!/usr/bin/env python3
"""Writes bend-engine/model_vectors.txt: the Lean model's merge results on every pair of maps in a bounded
domain. tests/merge_bend.test.ts checks that the compiled Bend merge gives the same results on the same pairs.

The domain: sorted maps over the keys "a" and "b" (the empty map, one key, or both keys), with values drawn from
a few fixed ones that include ties and an absent entry. Lessons: 3 values; SRS cards: 4 values, one
differing in ease, one with no lastReview, one with reps 2; XP: 3 values. The Lean model computes the results
(`mergeMap` of Merge.lean, which is the model of merge.bend); nothing else is enumerated.

Run from anywhere: python3 bend-engine/model_vectors.py [--out PATH]
Requires lean 4.34.0 (see LEAN_BIN below). The output is committed; the test regenerates it and compares.
"""
import argparse
import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
MERGE = os.path.join(HERE, "Merge.lean")
DEFAULT_OUT = os.path.join(HERE, "model_vectors.txt")
LEAN_BIN = os.environ.get("LEAN_BIN", "/root/.elan/toolchains/leanprover--lean4---v4.34.0/bin")

GENERATOR = r'''
section Vectors
open BendMerge

def showLesson (l : Lesson) : String :=
  toString l.crowns ++ "," ++ toString l.attempts ++ "," ++ toString l.best ++ "," ++ toString l.played

def showLast : Option Nat → String
  | none => "-"
  | some x => toString x

def showCard (c : Card) : String :=
  c.id ++ "," ++ c.lessonId ++ "," ++ toString c.interval ++ "," ++ toString c.ease ++ "," ++
    toString c.due ++ "," ++ toString c.lapses ++ "," ++ toString c.reps ++ "," ++ showLast c.last

def showEntries {α : Type} (f : α → String) (xs : List (Entry α)) : String :=
  String.intercalate ";" (xs.map fun e => e.key ++ "=" ++ f e.val)

-- every sorted map over the keys "a" and "b", with values from vals
def maps {α : Type} (vals : List α) : List (List (Entry α)) :=
  [[]] ++ vals.map (fun v => [⟨"a", v⟩]) ++ vals.map (fun v => [⟨"b", v⟩]) ++
    vals.flatMap (fun v1 => vals.map (fun v2 => [⟨"a", v1⟩, ⟨"b", v2⟩]))

def lessonVals : List Lesson := [⟨0, 0, 0, 0⟩, ⟨1, 2, 3, 4⟩, ⟨2, 1, 0, 5⟩]
def cardA : Card := ⟨"x", "l", 1, 200, 5, 0, 1, some 7⟩
def cardVals : List Card :=
  [cardA, { cardA with ease := 250 }, { cardA with last := none }, { cardA with reps := 2 }]
def xpVals : List Nat := [0, 5, 10]

def emit : IO Unit := do
  for a in maps lessonVals do
    for b in maps lessonVals do
      IO.println s!"V|L|{showEntries showLesson a}|{showEntries showLesson b}|{showEntries showLesson (mergeMap lpMax a b)}"
  for a in maps cardVals do
    for b in maps cardVals do
      IO.println s!"V|C|{showEntries showCard a}|{showEntries showCard b}|{showEntries showCard (mergeMap cardMerge a b)}"
  for a in maps xpVals do
    for b in maps xpVals do
      IO.println s!"V|X|{showEntries toString a}|{showEntries toString b}|{showEntries toString (mergeMap Nat.max a b)}"

#eval emit
end Vectors
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=DEFAULT_OUT)
    args = ap.parse_args()
    with open(MERGE) as f:
        model = f.read()
    tmp = tempfile.mkdtemp(prefix="mv-")
    src = os.path.join(tmp, "Vectors.lean")
    with open(src, "w") as f:
        f.write(model + "\n" + GENERATOR)
    env = dict(os.environ, PATH=LEAN_BIN + os.pathsep + os.environ.get("PATH", ""))
    run = subprocess.run(["lean", src], capture_output=True, text=True, env=env, timeout=900)
    if run.returncode != 0:
        sys.stderr.write(run.stdout + run.stderr)
        return run.returncode
    rows = [l for l in run.stdout.split("\n") if l.startswith("V|")]
    if not rows:
        sys.stderr.write("the model produced no vectors\n")
        return 1
    with open(args.out, "w") as f:
        f.write("# Generated by bend-engine/model_vectors.py from Merge.lean. Do not edit by hand.\n")
        f.write("# Each line: V|kind|map a|map b|mergeMap a b (kind L: lessons, C: SRS cards, X: XP per day)\n")
        f.write("\n".join(rows) + "\n")
    print(f"{len(rows)} vectors written to {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
